using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Nullify.WebMail.Services;

// The rule editor's model of a Sieve script (RFC 5228): a flat list of "if <test> { actions }"
// blocks. SieveRuleParser maps a script onto it only when that is lossless (comments aside);
// anything else stays in the raw text editor. Rule names and disabled rules follow Roundcube's
// conventions ("# rule:[name]", "if false # <test>") so its scripts open here too.

public enum SieveField { From, To, Cc, ToOrCc, ReplyTo, Subject, ListId, Header, Body, Size }

public enum SieveOp { Contains, Is, StartsWith, EndsWith, Matches, Regex, Exists, Over, Under }

public enum SieveActionKind { FileInto, CopyTo, Redirect, RedirectCopy, MarkRead, Flag, AddFlag, Discard, Reject, Keep, Vacation }

public sealed class SieveCondition
{
    public SieveField Field { get; set; } = SieveField.From;
    /// <summary>Header names for <see cref="SieveField.Header"/>, comma separated.</summary>
    public string HeaderName { get; set; } = "";
    public SieveOp Op { get; set; } = SieveOp.Contains;
    public bool Negate { get; set; }
    /// <summary>Alternatives: the condition matches if any one of them does.</summary>
    public List<string> Values { get; set; } = [""];
    /// <summary>"address" or "header"; null means the field's natural test.</summary>
    public string? Test { get; set; }
    /// <summary>Address part tag (":localpart", ":domain") kept from a parsed script.</summary>
    public string? AddressPart { get; set; }

    public static bool IsAddressField(SieveField f) =>
        f is SieveField.From or SieveField.To or SieveField.Cc or SieveField.ToOrCc or SieveField.ReplyTo;
}

public sealed class SieveAction
{
    public SieveActionKind Kind { get; set; } = SieveActionKind.FileInto;
    /// <summary>Folder, address, flag or reject message, depending on <see cref="Kind"/>.</summary>
    public string Argument { get; set; } = "";
    public int VacationDays { get; set; } = 7;
    public string VacationSubject { get; set; } = "";
}

public sealed class SieveRule
{
    public string Name { get; set; } = "";
    public bool Enabled { get; set; } = true;
    public bool MatchAll { get; set; } = true;
    /// <summary>Empty means every message.</summary>
    public List<SieveCondition> Conditions { get; set; } = [];
    public List<SieveAction> Actions { get; set; } = [];
    public bool Stop { get; set; }
}

public sealed record SieveParseResult(List<SieveRule>? Rules, string? Error, bool DropsComments = false);

public sealed class SieveSyntaxException(string message) : Exception(message);

public static class SieveRuleWriter
{
    public const string Header = "# Generated by Nullify WebMail";

    public static string Write(IReadOnlyList<SieveRule> rules)
    {
        var sb = new StringBuilder();
        sb.Append(Header).Append('\n');
        var requires = Requirements(rules);
        if (requires.Count > 0)
            sb.Append("require ").Append(StringList(requires)).Append(";\n");
        foreach (var rule in rules)
        {
            sb.Append('\n');
            if (rule.Name.Length > 0) sb.Append("# rule:[").Append(rule.Name.ReplaceLineEndings(" ")).Append("]\n");
            var test = TopTest(rule);
            sb.Append(rule.Enabled ? $"if {test}\n" : $"if allof (false, {test})\n");
            sb.Append("{\n");
            foreach (var action in rule.Actions)
                sb.Append("    ").Append(Action(action)).Append(";\n");
            if (rule.Stop) sb.Append("    stop;\n");
            sb.Append("}\n");
        }
        return sb.ToString();
    }

    private static List<string> Requirements(IReadOnlyList<SieveRule> rules)
    {
        var set = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var rule in rules)
        {
            foreach (var c in rule.Conditions)
            {
                if (c.Op == SieveOp.Regex) set.Add("regex");
                if (c.Field == SieveField.Body && c.Op != SieveOp.Exists) set.Add("body");
            }
            foreach (var a in rule.Actions)
            {
                switch (a.Kind)
                {
                    case SieveActionKind.FileInto: set.Add("fileinto"); break;
                    case SieveActionKind.CopyTo: set.Add("fileinto"); set.Add("copy"); break;
                    case SieveActionKind.RedirectCopy: set.Add("copy"); break;
                    case SieveActionKind.MarkRead or SieveActionKind.Flag or SieveActionKind.AddFlag: set.Add("imap4flags"); break;
                    case SieveActionKind.Reject: set.Add("reject"); break;
                    case SieveActionKind.Vacation: set.Add("vacation"); break;
                }
            }
        }
        return set.ToList();
    }

    private static string TopTest(SieveRule rule)
    {
        if (rule.Conditions.Count == 0) return "true";
        if (rule.Conditions.Count == 1) return Condition(rule.Conditions[0]);
        return (rule.MatchAll ? "allof" : "anyof") + " (" + string.Join(", ", rule.Conditions.Select(Condition)) + ")";
    }

    public static string Condition(SieveCondition c)
    {
        var headers = HeaderNames(c);
        string test;
        if (c.Op == SieveOp.Exists)
            test = "exists " + StringList(headers);
        else if (c.Field == SieveField.Size)
            test = $"size {(c.Op == SieveOp.Under ? ":under" : ":over")} {NormaliseSize(c.Values.FirstOrDefault())}";
        else
        {
            var match = c.Op switch
            {
                SieveOp.Is => ":is",
                SieveOp.StartsWith or SieveOp.EndsWith or SieveOp.Matches => ":matches",
                SieveOp.Regex => ":regex",
                _ => ":contains",
            };
            var values = c.Values.Where(v => v.Length > 0).DefaultIfEmpty("").Select(v => c.Op switch
            {
                SieveOp.StartsWith => EscapeWildcards(v) + "*",
                SieveOp.EndsWith => "*" + EscapeWildcards(v),
                _ => v,
            }).ToList();
            if (c.Field == SieveField.Body)
                test = $"body :text {match} {StringList(values)}";
            else
            {
                var kind = c.Test ?? (SieveCondition.IsAddressField(c.Field) ? "address" : "header");
                var part = kind == "address" && c.AddressPart is { } p ? p + " " : "";
                test = $"{kind} {part}{match} {StringList(headers)} {StringList(values)}";
            }
        }
        return c.Negate ? "not " + test : test;
    }

    public static List<string> HeaderNames(SieveCondition c) => c.Field switch
    {
        SieveField.From => ["from"],
        SieveField.To => ["to"],
        SieveField.Cc => ["cc"],
        SieveField.ToOrCc => ["to", "cc"],
        SieveField.ReplyTo => ["reply-to"],
        SieveField.Subject => ["subject"],
        SieveField.ListId => ["list-id"],
        _ => c.HeaderName.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .DefaultIfEmpty("x-unnamed").ToList(),
    };

    private static string Action(SieveAction a) => a.Kind switch
    {
        SieveActionKind.FileInto => "fileinto " + Quote(a.Argument),
        SieveActionKind.CopyTo => "fileinto :copy " + Quote(a.Argument),
        SieveActionKind.Redirect => "redirect " + Quote(a.Argument),
        SieveActionKind.RedirectCopy => "redirect :copy " + Quote(a.Argument),
        SieveActionKind.MarkRead => "addflag \"\\\\Seen\"",
        SieveActionKind.Flag => "addflag \"\\\\Flagged\"",
        SieveActionKind.AddFlag => "addflag " + Quote(a.Argument),
        SieveActionKind.Discard => "discard",
        SieveActionKind.Reject => "reject " + Quote(a.Argument),
        SieveActionKind.Keep => "keep",
        SieveActionKind.Vacation => $"vacation :days {Math.Max(1, a.VacationDays)}"
            + (a.VacationSubject.Length > 0 ? " :subject " + Quote(a.VacationSubject) : "")
            + " " + Quote(a.Argument),
        _ => throw new ArgumentOutOfRangeException(nameof(a)),
    };

    private static string NormaliseSize(string? v)
    {
        var m = Regex.Match(v ?? "", @"^\s*(\d+)\s*([KMG]?)\s*$", RegexOptions.IgnoreCase);
        return m.Success ? m.Groups[1].Value + m.Groups[2].Value.ToUpperInvariant() : "0";
    }

    public static string EscapeWildcards(string v) =>
        v.Replace("\\", "\\\\").Replace("*", "\\*").Replace("?", "\\?");

    public static string Quote(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string StringList(IReadOnlyList<string> items) =>
        items.Count == 1 ? Quote(items[0]) : "[" + string.Join(", ", items.Select(Quote)) + "]";
}

public static class SieveRuleParser
{
    public static SieveParseResult Parse(string script)
    {
        try
        {
            var p = new SieveSyntaxParser(script);
            var commands = p.ParseScript();
            var rules = new List<SieveRule>();
            var dropsComments = false;
            for (var i = 0; i < commands.Count; i++)
            {
                var cmd = commands[i];
                string? name = null;
                foreach (var comment in cmd.Comments)
                {
                    var m = Regex.Match(comment, @"^\s*rule:\[(.*)\]\s*$");
                    if (m.Success) name = m.Groups[1].Value;
                    else if (!comment.TrimStart('#', ' ').StartsWith("Generated by", StringComparison.Ordinal))
                        dropsComments = true;
                }
                if (cmd.Name == "require") continue;
                if (cmd.Name != "if" || cmd.Block == null || cmd.Tests.Count != 1)
                    throw Unsupported($"the \"{cmd.Name}\" command outside a rule");
                if (i + 1 < commands.Count && commands[i + 1].Name is "elsif" or "else")
                    throw Unsupported("elsif/else chains");
                var rule = new SieveRule { Name = name ?? "" };
                MapTopTest(rule, cmd.Tests[0], cmd.InlineComments);
                MapActions(rule, cmd.Block);
                if (cmd.InlineComments.Count > 0 && rule.Enabled) dropsComments = true;
                rules.Add(rule);
            }
            dropsComments |= p.InnerCommentCount > 0;
            return new SieveParseResult(rules, null, dropsComments);
        }
        catch (SieveSyntaxException ex)
        {
            return new SieveParseResult(null, ex.Message);
        }
    }

    private static SieveSyntaxException Unsupported(string what) =>
        new($"The rule editor doesn't support {what}.");

    private static void MapTopTest(SieveRule rule, SieveTest test, List<string> inlineComments)
    {
        if (test.Name == "true" && test.Args.Count == 0) return;
        if (test.Name == "false" && test.Args.Count == 0)
        {
            // Roundcube disables a rule as "if false # <original test>".
            if (inlineComments.Count == 0) throw Unsupported("an \"if false\" rule");
            rule.Enabled = false;
            var inner = new SieveSyntaxParser(inlineComments[0]).ParseLoneTest();
            MapTopTest(rule, inner, []);
            return;
        }
        if (test.Name is "allof" or "anyof")
        {
            var tests = test.Tests.ToList();
            if (test.Name == "allof" && tests.Count > 0 && tests[0] is { Name: "false", Args.Count: 0 })
            {
                rule.Enabled = false;
                tests.RemoveAt(0);
                if (tests.Count == 1) { MapTopTest(rule, tests[0], []); return; }
                if (tests.Count == 0) throw Unsupported("an empty disabled rule");
            }
            rule.MatchAll = test.Name == "allof";
            foreach (var t in tests) rule.Conditions.Add(MapCondition(t));
            return;
        }
        rule.Conditions.Add(MapCondition(test));
    }

    private static SieveCondition MapCondition(SieveTest test)
    {
        var negate = false;
        if (test.Name == "not")
        {
            if (test.Tests.Count != 1) throw Unsupported("this \"not\" test");
            negate = true;
            test = test.Tests[0];
        }
        var c = new SieveCondition { Negate = negate };
        switch (test.Name)
        {
            case "size":
            {
                var tag = test.Tags.SingleOrDefault();
                if (tag is not (":over" or ":under") || test.Numbers.Count != 1 || test.StringLists.Count != 0 || test.Tests.Count != 0)
                    throw Unsupported("this size test");
                c.Field = SieveField.Size;
                c.Op = tag == ":over" ? SieveOp.Over : SieveOp.Under;
                c.Values = [test.Numbers[0]];
                return c;
            }
            case "exists":
            {
                if (test.StringLists.Count != 1 || test.Args.Count != 1) throw Unsupported("this exists test");
                SetHeaders(c, test.StringLists[0]);
                c.Op = SieveOp.Exists;
                return c;
            }
            case "address" or "header" or "body":
            {
                if (test.Numbers.Count != 0 || test.Tests.Count != 0) throw Unsupported($"this {test.Name} test");
                string? match = null;
                var tags = test.Tags;
                for (var i = 0; i < tags.Count; i++)
                {
                    var t = tags[i];
                    if (t is ":is" or ":contains" or ":matches" or ":regex" && match == null) match = t;
                    else if (t == ":comparator")
                    {
                        // The comparator's name is the string list that follows the tag.
                        var idx = test.Args.FindIndex(a => a.Tag == ":comparator");
                        if (idx + 1 >= test.Args.Count || test.Args[idx + 1].Strings is not [var cmp]
                            || !cmp.Equals("i;ascii-casemap", StringComparison.OrdinalIgnoreCase))
                            throw Unsupported("comparators other than i;ascii-casemap");
                        test.Args.RemoveAt(idx + 1);
                    }
                    else if (test.Name == "address" && t is ":all" or ":localpart" or ":domain" && c.AddressPart == null)
                        c.AddressPart = t == ":all" ? null : t;
                    else if (test.Name == "body" && t == ":text") { }
                    else throw Unsupported($"the {t} option");
                }
                var lists = test.StringLists;
                var expected = test.Name == "body" ? 1 : 2;
                if (lists.Count != expected) throw Unsupported($"this {test.Name} test");
                var keys = lists[^1];
                if (test.Name == "body") c.Field = SieveField.Body;
                else
                {
                    SetHeaders(c, lists[0]);
                    var natural = SieveCondition.IsAddressField(c.Field) ? "address" : "header";
                    if (test.Name != natural) c.Test = test.Name;
                }
                c.Op = match switch
                {
                    ":is" => SieveOp.Is,
                    ":matches" => SieveOp.Matches,
                    ":regex" => SieveOp.Regex,
                    _ => SieveOp.Contains,
                };
                c.Values = keys.ToList();
                if (c.Op == SieveOp.Matches) RecogniseAffix(c);
                return c;
            }
            default:
                throw Unsupported($"the \"{test.Name}\" test");
        }
    }

    private static void SetHeaders(SieveCondition c, List<string> headers)
    {
        var lower = headers.Select(h => h.ToLowerInvariant()).ToList();
        c.Field = lower switch
        {
            ["from"] => SieveField.From,
            ["to"] => SieveField.To,
            ["cc"] => SieveField.Cc,
            ["to", "cc"] or ["cc", "to"] => SieveField.ToOrCc,
            ["reply-to"] => SieveField.ReplyTo,
            ["subject"] => SieveField.Subject,
            ["list-id"] => SieveField.ListId,
            _ => SieveField.Header,
        };
        if (c.Field == SieveField.Header) c.HeaderName = string.Join(", ", headers);
    }

    // "foo*" / "*foo" with no other wildcards read back as starts-with / ends-with.
    private static void RecogniseAffix(SieveCondition c)
    {
        if (Literals(c.Values, v => v.EndsWith('*') ? v[..^1] : null) is { } prefixes)
        {
            c.Op = SieveOp.StartsWith;
            c.Values = prefixes;
        }
        else if (Literals(c.Values, v => v.StartsWith('*') ? v[1..] : null) is { } suffixes)
        {
            c.Op = SieveOp.EndsWith;
            c.Values = suffixes;
        }
    }

    private static List<string>? Literals(List<string> patterns, Func<string, string?> core)
    {
        var result = new List<string>();
        foreach (var p in patterns)
        {
            if (core(p) is not { Length: > 0 } k || UnescapeLiteral(k) is not { } literal) return null;
            result.Add(literal);
        }
        return result.Count > 0 ? result : null;
    }

    /// <summary>Undoes <see cref="SieveRuleWriter.EscapeWildcards"/>; null if the pattern has live wildcards.</summary>
    private static string? UnescapeLiteral(string pattern)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < pattern.Length; i++)
        {
            var ch = pattern[i];
            if (ch == '\\')
            {
                if (i + 1 >= pattern.Length) return null;
                sb.Append(pattern[++i]);
            }
            else if (ch is '*' or '?') return null;
            else sb.Append(ch);
        }
        return sb.ToString();
    }

    private static void MapActions(SieveRule rule, List<SieveCommand> block)
    {
        for (var i = 0; i < block.Count; i++)
        {
            var cmd = block[i];
            if (cmd.Block != null || cmd.Tests.Count != 0) throw Unsupported($"nested \"{cmd.Name}\" blocks");
            var tags = cmd.Tags;
            var lists = cmd.StringLists;
            switch (cmd.Name)
            {
                case "stop" when cmd.Args.Count == 0:
                    if (i != block.Count - 1) throw Unsupported("\"stop\" before other actions");
                    rule.Stop = true;
                    break;
                case "keep" when cmd.Args.Count == 0:
                    rule.Actions.Add(new SieveAction { Kind = SieveActionKind.Keep });
                    break;
                case "discard" when cmd.Args.Count == 0:
                    rule.Actions.Add(new SieveAction { Kind = SieveActionKind.Discard });
                    break;
                case "fileinto" or "redirect" when lists is [[var target]] && tags.All(t => t == ":copy") && tags.Count <= 1:
                {
                    var copy = tags.Count == 1;
                    var kind = cmd.Name == "fileinto"
                        ? (copy ? SieveActionKind.CopyTo : SieveActionKind.FileInto)
                        : (copy ? SieveActionKind.RedirectCopy : SieveActionKind.Redirect);
                    rule.Actions.Add(new SieveAction { Kind = kind, Argument = target });
                    break;
                }
                case "reject" when lists is [[var message]] && tags.Count == 0:
                    rule.Actions.Add(new SieveAction { Kind = SieveActionKind.Reject, Argument = message });
                    break;
                case "addflag" when lists is [var flags] && tags.Count == 0 && cmd.Args.Count == 1:
                    foreach (var flag in flags)
                    {
                        rule.Actions.Add(flag.ToLowerInvariant() switch
                        {
                            "\\seen" => new SieveAction { Kind = SieveActionKind.MarkRead },
                            "\\flagged" => new SieveAction { Kind = SieveActionKind.Flag },
                            _ => new SieveAction { Kind = SieveActionKind.AddFlag, Argument = flag },
                        });
                    }
                    break;
                case "vacation":
                    rule.Actions.Add(MapVacation(cmd));
                    break;
                default:
                    throw Unsupported($"the \"{cmd.Name}\" action as written");
            }
        }
    }

    private static SieveAction MapVacation(SieveCommand cmd)
    {
        var action = new SieveAction { Kind = SieveActionKind.Vacation };
        var args = cmd.Args;
        var i = 0;
        for (; i < args.Count - 1; i++)
        {
            switch (args[i].Tag)
            {
                case ":days" when args[i + 1].Number is { } n:
                    action.VacationDays = int.TryParse(n, NumberStyles.None, CultureInfo.InvariantCulture, out var d) ? d : 7;
                    i++;
                    break;
                case ":subject" when args[i + 1].Strings is [var s]:
                    action.VacationSubject = s;
                    i++;
                    break;
                default:
                    throw Unsupported("these vacation options");
            }
        }
        if (i != args.Count - 1 || args[i].Strings is not [var reason]) throw Unsupported("this vacation action");
        action.Argument = reason;
        return action;
    }
}

// ---- generic Sieve syntax (RFC 5228 section 8) ----

internal sealed class SieveArg
{
    public string? Tag { get; init; }
    public string? Number { get; init; }
    public List<string>? Strings { get; init; }
}

internal class SieveTest
{
    public required string Name { get; init; }
    public List<SieveArg> Args { get; } = [];
    public List<SieveTest> Tests { get; } = [];
    public List<string> Tags => Args.Where(a => a.Tag != null).Select(a => a.Tag!.ToLowerInvariant()).ToList();
    public List<string> Numbers => Args.Where(a => a.Number != null).Select(a => a.Number!).ToList();
    public List<List<string>> StringLists => Args.Where(a => a.Strings != null).Select(a => a.Strings!).ToList();
}

internal sealed class SieveCommand : SieveTest
{
    public List<SieveCommand>? Block { get; set; }
    /// <summary>Comments directly before the command.</summary>
    public List<string> Comments { get; init; } = [];
    /// <summary>Comments between the test and the opening brace.</summary>
    public List<string> InlineComments { get; set; } = [];
}

internal sealed class SieveSyntaxParser(string text)
{
    private int _pos;
    private int _line = 1;
    private readonly List<string> _pending = [];
    private int _depth;

    /// <summary>Comments found inside blocks or argument lists, which the rule model can't keep.</summary>
    public int InnerCommentCount { get; private set; }

    public List<SieveCommand> ParseScript() => ParseCommands(topLevel: true);

    public SieveTest ParseLoneTest()
    {
        var t = ParseTest();
        SkipTrivia();
        if (_pos < text.Length) throw Error("unexpected text after test");
        return t;
    }

    private List<SieveCommand> ParseCommands(bool topLevel)
    {
        var list = new List<SieveCommand>();
        while (true)
        {
            SkipTrivia();
            if (_pos >= text.Length)
            {
                if (!topLevel) throw Error("missing '}'");
                if (_pending.Count > 0) InnerCommentCount += _pending.Count;
                return list;
            }
            if (text[_pos] == '}')
            {
                if (topLevel) throw Error("unexpected '}'");
                InnerCommentCount += _pending.Count;
                _pending.Clear();
                _pos++;
                return list;
            }
            var comments = _pending.ToList();
            _pending.Clear();
            if (!topLevel) InnerCommentCount += comments.Count;
            var cmd = new SieveCommand { Name = ReadIdentifier(), Comments = comments };
            ParseArguments(cmd);
            SkipTrivia();
            if (_pos >= text.Length) throw Error($"missing ';' after {cmd.Name}");
            if (text[_pos] == ';') _pos++;
            else if (text[_pos] == '{')
            {
                cmd.InlineComments = _pending.ToList();
                _pending.Clear();
                _pos++;
                _depth++;
                cmd.Block = ParseCommands(topLevel: false);
                _depth--;
            }
            else throw Error($"expected ';' or '{{' after {cmd.Name}");
            if (_depth > 0) InnerCommentCount += cmd.InlineComments.Count;
            list.Add(cmd);
        }
    }

    private void ParseArguments(SieveTest node)
    {
        while (true)
        {
            SkipTrivia();
            if (_pos >= text.Length) return;
            var ch = text[_pos];
            if (ch == ':')
            {
                _pos++;
                node.Args.Add(new SieveArg { Tag = ":" + ReadIdentifier() });
            }
            else if (char.IsAsciiDigit(ch)) node.Args.Add(new SieveArg { Number = ReadNumber() });
            else if (ch is '"' or '[' || StartsMultiline()) node.Args.Add(new SieveArg { Strings = ReadStringList() });
            else break;
        }
        SkipTrivia();
        if (_pos >= text.Length) return;
        if (text[_pos] == '(')
        {
            _pos++;
            while (true)
            {
                node.Tests.Add(ParseTest());
                SkipInnerTrivia();
                if (_pos >= text.Length) throw Error("missing ')'");
                if (text[_pos] == ',') { _pos++; continue; }
                if (text[_pos] == ')') { _pos++; break; }
                throw Error("expected ',' or ')' in test list");
            }
        }
        else if (IsIdentifierStart(text[_pos]))
            node.Tests.Add(ParseTest());
    }

    private SieveTest ParseTest()
    {
        SkipInnerTrivia();
        var t = new SieveTest { Name = ReadIdentifier() };
        ParseArguments(t);
        return t;
    }

    private List<string> ReadStringList()
    {
        if (text[_pos] != '[') return [ReadString()];
        _pos++;
        var list = new List<string>();
        while (true)
        {
            SkipInnerTrivia();
            if (_pos >= text.Length) throw Error("missing ']'");
            list.Add(ReadString());
            SkipInnerTrivia();
            if (_pos >= text.Length) throw Error("missing ']'");
            if (text[_pos] == ',') { _pos++; continue; }
            if (text[_pos] == ']') { _pos++; return list; }
            throw Error("expected ',' or ']' in string list");
        }
    }

    private string ReadString()
    {
        if (StartsMultiline()) return ReadMultiline();
        if (_pos >= text.Length || text[_pos] != '"') throw Error("expected a string");
        _pos++;
        var sb = new StringBuilder();
        while (true)
        {
            if (_pos >= text.Length) throw Error("unterminated string");
            var ch = text[_pos++];
            if (ch == '"') return sb.ToString();
            if (ch == '\\')
            {
                if (_pos >= text.Length) throw Error("unterminated string");
                ch = text[_pos++];
            }
            if (ch == '\n') _line++;
            sb.Append(ch);
        }
    }

    private bool StartsMultiline() =>
        string.CompareOrdinal(text, _pos, "text:", 0, 5) == 0;

    private string ReadMultiline()
    {
        _pos += 5;
        while (_pos < text.Length && text[_pos] is ' ' or '\t') _pos++;
        if (_pos < text.Length && text[_pos] == '#')
            while (_pos < text.Length && text[_pos] != '\n') _pos++;
        if (_pos < text.Length && text[_pos] == '\r') _pos++;
        if (_pos >= text.Length || text[_pos] != '\n') throw Error("expected a line break after text:");
        _pos++;
        _line++;
        var sb = new StringBuilder();
        while (true)
        {
            if (_pos >= text.Length) throw Error("unterminated text: block");
            var end = text.IndexOf('\n', _pos);
            var lineText = (end < 0 ? text[_pos..] : text[_pos..end]).TrimEnd('\r');
            _pos = end < 0 ? text.Length : end + 1;
            _line++;
            if (lineText == ".") return sb.ToString();
            if (lineText.StartsWith("..", StringComparison.Ordinal)) lineText = lineText[1..];
            sb.Append(lineText).Append('\n');
        }
    }

    private string ReadNumber()
    {
        var start = _pos;
        while (_pos < text.Length && char.IsAsciiDigit(text[_pos])) _pos++;
        if (_pos < text.Length && "KMGkmg".Contains(text[_pos])) _pos++;
        return text[start.._pos].ToUpperInvariant();
    }

    private string ReadIdentifier()
    {
        if (_pos >= text.Length || !IsIdentifierStart(text[_pos])) throw Error("expected a command or test name");
        var start = _pos;
        while (_pos < text.Length && (char.IsAsciiLetterOrDigit(text[_pos]) || text[_pos] == '_')) _pos++;
        return text[start.._pos].ToLowerInvariant();
    }

    private static bool IsIdentifierStart(char c) => char.IsAsciiLetter(c) || c == '_';

    // Comments inside a test or string list can't be kept by the rule model.
    private void SkipInnerTrivia()
    {
        var before = _pending.Count;
        SkipTrivia();
        InnerCommentCount += _pending.Count - before;
        _pending.RemoveRange(before, _pending.Count - before);
    }

    private void SkipTrivia()
    {
        while (_pos < text.Length)
        {
            var ch = text[_pos];
            if (ch == '\n') { _line++; _pos++; }
            else if (char.IsWhiteSpace(ch)) _pos++;
            else if (ch == '#')
            {
                var end = text.IndexOf('\n', _pos);
                if (end < 0) end = text.Length;
                _pending.Add(text[(_pos + 1)..end].TrimEnd('\r'));
                _pos = end;
            }
            else if (ch == '/' && _pos + 1 < text.Length && text[_pos + 1] == '*')
            {
                var end = text.IndexOf("*/", _pos + 2, StringComparison.Ordinal);
                if (end < 0) throw Error("unterminated comment");
                var body = text[(_pos + 2)..end];
                _line += body.Count(c => c == '\n');
                _pending.Add(body);
                _pos = end + 2;
            }
            else break;
        }
    }

    private SieveSyntaxException Error(string message) => new($"Line {_line}: {message}.");
